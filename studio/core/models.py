class ExtResourceAST(BaseModel):
    """External resource link in Godot .tscn (textures, audio streams, scripts)."""
    id: str                                # e.g. "1_tex", "2_script"
    type: str                              # "Texture2D", "AudioStream", "Script"
    path: str                              # "res://assets/sprites/player.png"


class NodeAST(BaseModel):
    """Node definition within a scene graph."""
    name: str                              # "Player", "Sprite2D", "CollisionShape2D"
    type: str                              # Godot class: "CharacterBody2D", "Sprite2D"
    parent: Optional[str] = None           # None = root, "." = direct child of root
    instance: Optional[str] = None
    properties: Dict[str, Any] = Field(default_factory=dict)
    script_id: Optional[str] = None        # ExtResource id of attached script

    @property
    def is_root(self) -> bool:
        return self.parent is None


class ConnectionAST(BaseModel):
    """Signal wiring between scene nodes."""
    signal: str                            # e.g., "body_entered", "pressed"
    from_node: str                         # "Area2D"
    to_node: str                           # "." (root)
    method: str                            # "_on_body_entered"
    flags: Optional[int] = None


class SceneAST(BaseModel):
    """Abstract Syntax Tree representing a game scene (.tscn / JSON)."""
    model_config = ConfigDict(populate_by_name=True)

    name: str
    path: str                              # "scenes/player.tscn"
    format_version: int = 3
    ext_resources: List[ExtResourceAST] = Field(default_factory=list)
    sub_resources: List[Any] = Field(default_factory=list)
    nodes: List[NodeAST] = Field(default_factory=list)
    connections: List[ConnectionAST] = Field(default_factory=list)


class ScriptSpec(BaseModel):
    """Game logic script file specification."""
    rel_path: str                          # "scripts/player.gd"
    language: str = "gdscript"             # "gdscript", "python", "javascript", "csharp"
    code: str                              # Complete executable source code
    description: Optional[str] = None
    extends_class: Optional[str] = None


