class AssetRequirement(BaseModel):
    """GDD specification of an asset required from the multimodal artist."""
    model_config = ConfigDict(populate_by_name=True)

    asset_id: str                          # e.g., "sprite_player", "sfx_jump"
    asset_type: Union[AssetType, str]      # "sprite", "audio_sfx", etc.
    description: str = ""
    target_rel_path: Optional[str] = None
    rel_path: Optional[str] = None
    prompt_hint: str = ""
    width: Optional[int] = None            # e.g., 32, 64, 512
    height: Optional[int] = None
    duration_sec: Optional[float] = None   # for audio clips
    tags: List[str] = Field(default_factory=list)

    @field_validator("rel_path", mode="before")
    @classmethod
    def _default_rel_path(cls, v: Any, info: Any) -> Any:
        return v

    def get_rel_path(self) -> str:
        """Resolves target relative path with reasonable default if unspecified."""
        if self.rel_path:
            return self.rel_path
        if self.target_rel_path:
            return self.target_rel_path
        atype = self.asset_type.value if isinstance(self.asset_type, AssetType) else str(self.asset_type)
        if "sprite" in atype or "texture" in atype:
            return f"assets/sprites/{self.asset_id}.png"
        elif "music" in atype:
            return f"audio/music/{self.asset_id}.wav"
        elif "audio" in atype or "sfx" in atype:
            return f"audio/sfx/{self.asset_id}.wav"
        elif "cutscene" in atype:
            return f"assets/cutscenes/{self.asset_id}.png"
        return f"assets/{self.asset_id}.dat"


class ScenePlan(BaseModel):
    """GDD structural layout for a game scene."""
    model_config = ConfigDict(populate_by_name=True)

    scene_id: Optional[str] = None
    name: Optional[str] = None
    scene_name: Optional[str] = None
    path: Optional[str] = None
    description: str = ""
    root_node_type: str = "Node2D"         # e.g., "Node2D", "CharacterBody2D", "Area2D"
    required_assets: List[str] = Field(default_factory=list)  # asset_ids
    required_scripts: List[str] = Field(default_factory=list)
    script_name: Optional[str] = None      # e.g., "scripts/player.gd"
    nodes_overview: List[Dict[str, str]] = Field(default_factory=list)

    def get_name(self) -> str:
        return self.name or self.scene_name or self.scene_id or "Scene"

    def get_path(self) -> str:
        if self.path:
            return self.path
        name = self.get_name().lower()
        return f"scenes/{name}.tscn"


