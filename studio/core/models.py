class AgentRole(str, Enum):
    """Rigidly defined agent roles enforcing tri-provider division of labor."""
    DIRECTOR = "openai_director"       # Story, GDD, Lore, Quests, Dialogues
    ARTIST = "gemini_artist"           # 2D Sprites, Textures, BGM, SFX, Cutscenes
    ENGINEER = "claude_engineer"       # Engine Architecture, GDScript/Code, Scenes
    ORCHESTRATOR = "orchestrator"     # Workflow coordinator & state machine
    VALIDATOR = "validator"           # Automated syntax, schema & simulation verifier
    USER = "user"                     # Human director / GUI operator


class EngineTarget(str, Enum):
    """Supported target game engines."""
    GODOT4 = "godot4"
    PYGAME = "pygame"
    WEB_HTML5 = "web_html5"
    UNITY = "unity"


class GameGenre(str, Enum):
    """Game genres supported across templates and generation pipelines."""
    PLATFORMER_2D = "platformer_2d"
    TOP_DOWN_RPG = "top_down_rpg"
    SPACE_SHOOTER = "space_shooter"
    GRID_PUZZLE = "grid_puzzle"
    ENDLESS_RUNNER = "endless_runner"
    CUSTOM = "custom"


class AssetType(str, Enum):
    """Categories of multimodal assets generated by Gemini / Mock."""
    SPRITE = "sprite"
    TEXTURE = "texture"
    AUDIO_SFX = "audio_sfx"
    AUDIO_MUSIC = "audio_music"
    CUTSCENE = "cutscene"
    TILEMAP = "tilemap"
    UI_ELEMENT = "ui_element"


class ProjectStatus(str, Enum):
    """Global project execution lifecycle status."""
    PENDING = "PENDING"
    IN_PROGRESS = "IN_PROGRESS"
    REVIEW_REQUIRED = "REVIEW_REQUIRED"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"


