class DiagnosticError(BaseModel):
    """Structured error or warning diagnosed during verification."""
    stage: str                             # "syntax_check", "schema_check", "asset_integrity", "simulation"
    severity: str = "ERROR"                # "ERROR", "WARNING", "INFO"
    file_path: str
    line: Optional[int] = None
    column: Optional[int] = None
    message: str
    suggested_fix: Optional[str] = None


class VerificationReport(BaseModel):
    """Comprehensive test and validation report from Verification Pipeline."""
    passed: bool
    stages_executed: List[str] = Field(default_factory=list)
    errors: List[DiagnosticError] = Field(default_factory=list)
    warnings: List[DiagnosticError] = Field(default_factory=list)
    execution_time_ms: float = 0.0
    simulation_frames_run: int = 0
    summary: str = ""


class ReviewFeedback(BaseModel):
    """Formal review feedback routed between agents when errors occur."""
    review_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    reviewer: AgentRole
    target_role: AgentRole
    target_artifact: str                   # File path or component name
    approved: bool
    comments: str = ""
    issues: List[str] = Field(default_factory=list)
    suggested_changes: List[str] = Field(default_factory=list)
    iteration_cycle: int = 1
    timestamp: float = Field(default_factory=time.time)


