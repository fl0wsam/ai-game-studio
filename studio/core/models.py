class AssetItem(BaseModel):
    """A generated media file (image, audio, cutscene) with path mappings."""
    model_config = ConfigDict(populate_by_name=True, arbitrary_types_allowed=True)

    asset_id: str
    asset_type: Union[AssetType, str]
    rel_path: str                          # Relative path on disk: "assets/sprites/player.png"
    engine_path: str = ""                  # Engine res:// path: "res://assets/sprites/player.png"
    file_bytes: Optional[bytes] = None     # In-memory raw bytes
    properties: Dict[str, Any] = Field(default_factory=dict) # width, height, sample_rate, format
    checksum: Optional[str] = None         # SHA-256 digest
    is_mock: bool = False

    def model_post_init(self, __context: Any) -> None:
        if not self.engine_path and self.rel_path:
            self.engine_path = f"res://{self.rel_path.lstrip('/')}"
        if self.file_bytes and not self.checksum:
            self.checksum = hashlib.sha256(self.file_bytes).hexdigest()

    @property
    def checksum_sha256(self) -> Optional[str]:
        if self.checksum:
            return self.checksum
        if self.file_bytes:
            self.checksum = hashlib.sha256(self.file_bytes).hexdigest()
            return self.checksum
        return None

    @field_serializer("file_bytes", when_used="json")
    def serialize_file_bytes(self, b: Optional[bytes]) -> Optional[str]:
        if b is None:
            return None
        return base64.b64encode(b).decode("ascii")

    @field_validator("file_bytes", mode="before")
    @classmethod
    def deserialize_file_bytes(cls, v: Any) -> Optional[bytes]:
        if v is None or isinstance(v, bytes):
            return v
        if isinstance(v, str):
            try:
                return base64.b64decode(v)
            except Exception:
                return v.encode("utf-8")
        return None


class AssetManifest(BaseModel):
    """Manifest of all multimodal assets generated for the project."""
    model_config = ConfigDict(populate_by_name=True)

    project_name: str
    items: List[AssetItem] = Field(default_factory=list)
    generated_at: float = Field(default_factory=time.time)
    generator_agent: AgentRole = AgentRole.ARTIST

    def get_item(self, asset_id: str) -> Optional[AssetItem]:
        for item in self.items:
            if item.asset_id == asset_id:
                return item
        return None

    def get_by_type(self, asset_type: Union[AssetType, str]) -> List[AssetItem]:
        val = asset_type.value if isinstance(asset_type, AssetType) else str(asset_type)
        return [
            i for i in self.items 
            if (isinstance(i.asset_type, AssetType) and i.asset_type.value == val) 
            or str(i.asset_type) == val
        ]

    def add_item(self, item: AssetItem) -> None:
        self.items = [i for i in self.items if i.asset_id != item.asset_id]
        self.items.append(item)


